"""The supply chain: what the engine is built from is exact, hash-checked, listed, and (when the network is there to say) still the answer to requirements.txt."""
import json
import os
import re
import sys
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "tools"))
import lock as locktool  # noqa: E402
import sbom as sbomtool  # noqa: E402

DIRECT = {}
for _line in (HERE / "requirements.txt").read_text(encoding="utf-8").splitlines():
    _line = _line.split("#", 1)[0].strip()
    if _line:
        _name, _, _ver = _line.partition("==")
        DIRECT[_name.strip().lower().replace("_", "-")] = _ver.strip()


def test_every_requirement_is_an_exact_version():
    for line in (HERE / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            assert re.fullmatch(r"[A-Za-z0-9_.\-]+==[0-9][^\s]*", line), f"'{line}' is not pinned to one version"


@pytest.mark.parametrize("name,dev", [("requirements.lock", False), ("requirements-dev.lock", True)])
def test_the_lock_lists_every_package_with_hashes(name, dev):
    text = (HERE / name).read_text(encoding="utf-8")
    pins = sbomtool.read_lock(HERE / name)
    assert pins, name
    assert len(pins) == len(re.findall(r"^[A-Za-z0-9_.\-]+==", text, re.M)), "a package the reader could not parse"
    for pkg, (version, hashes) in pins.items():
        assert hashes and all(re.fullmatch(r"[0-9a-f]{64}", h) for h in hashes), f"{pkg} has no usable hashes"
    for pkg, version in DIRECT.items():
        is_dev = pkg in locktool.DEV_ONLY
        if is_dev and not dev:
            assert pkg not in pins, f"{pkg} is a test tool and has no place in the lock the engine runs on"
        else:
            assert pins.get(pkg, (None,))[0] == version, f"{pkg}: requirements.txt says {version}, {name} says {pins.get(pkg)}"
    assert set(sbomtool.read_lock(HERE / "requirements.lock")) <= set(pins)


def test_the_solver_libraries_are_in_the_lock_at_the_pinned_versions():
    pins = sbomtool.read_lock(HERE / "requirements.lock")
    for pkg in ("ortools", "scipy", "numpy", "grpcio", "protobuf", "statsmodels", "scikit-learn", "pandas"):
        assert pkg in pins, pkg


def test_the_bill_of_materials_is_the_lock_in_cyclonedx_form():
    bom = json.loads((HERE.parent.parent / "docs" / "sbom" / "engine.cdx.json").read_text(encoding="utf-8"))
    pins = sbomtool.read_lock(HERE / "requirements.lock")
    assert bom["bomFormat"] == "CycloneDX" and bom["specVersion"] == "1.5"
    got = {c["name"].lower().replace("_", "-"): c for c in bom["components"]}
    assert set(got) == set(pins), f"the SBOM and the lock list different packages: {set(got) ^ set(pins)}"
    for pkg, c in got.items():
        version, hashes = pins[pkg]
        assert c["version"] == version and c["purl"] == f"pkg:pypi/{pkg}@{version}"
        assert sorted(h["content"] for h in c["hashes"]) == sorted(hashes)
        assert c["licenses"], f"{pkg} has no license entry"
    refs = {c["bom-ref"] for c in bom["components"]}
    for d in bom["dependencies"]:
        assert set(d["dependsOn"]) <= refs
    assert any(d["dependsOn"] for d in bom["dependencies"][1:]), "the SBOM records what depends on what"


def test_the_docker_build_installs_only_the_locked_set():
    dockerfile = (HERE.parent.parent / "docker" / "Dockerfile.backend").read_text(encoding="utf-8")
    assert "pip install --require-hashes --no-deps -r requirements.lock" in dockerfile


@pytest.mark.skipif(os.environ.get("ENGINE_TEST_NETWORK") != "1", reason="resolves against pypi.org (set ENGINE_TEST_NETWORK=1)")
def test_the_lock_is_still_what_requirements_txt_resolves_to():
    prod, dev = locktool.build("linux", "3.12")
    assert locktool.parse_lock(prod) == locktool.parse_lock((HERE / "requirements.lock").read_text(encoding="utf-8"))
    assert locktool.parse_lock(dev) == locktool.parse_lock((HERE / "requirements-dev.lock").read_text(encoding="utf-8"))


def test_the_generated_stubs_come_from_the_locked_toolchain():
    """Stubs generated by a newer grpcio-tools demand a newer protobuf than the lock allows (the engine would not start on the locked packages)."""
    pins = sbomtool.read_lock(HERE / "requirements.lock")
    stub = (HERE / "wfm_pb2_grpc.py").read_text(encoding="utf-8")
    assert f"GRPC_GENERATED_VERSION = '{pins['grpcio-tools'][0]}'" in stub
    gen = (HERE / "wfm_pb2.py").read_text(encoding="utf-8")
    major, minor = pins["protobuf"][0].split(".")[:2]
    m = re.search(r"Domain\.PUBLIC,\s*(\d+),\s*(\d+),", gen)
    assert (int(m.group(1)), int(m.group(2))) <= (int(major), int(minor)), "the generated code needs a newer protobuf runtime than the locked one"
