/**
 * Computes Staffing Requirement intervals using live Erlang C equations on forecast intervals.
 */
export function buildStaffingIntervals(intervals: ForecastInterval[]): StaffingRequirementInterval[] {
  return intervals.map((int) => {
    const solve = solveStaffingRequirement({
      volume: int.volume,
      intervalMinutes: int.intervalMinutes,
      ahtSeconds: int.ahtSeconds,
      targetSlaPercent: int.serviceGoalPercent / 100,
      targetSlaSeconds: int.thresholdSeconds,
      maxOccupancy: 0.85,
      shrinkagePercent: 0.22,
    });

    // Realistic scheduled staffing numbers across our roster
    let scheduledStaff = solve.grossStaffRequired;
    // Introduce intentional tactical delta at 14:00 to illustrate real-world operational pressure!
    if (int.intervalStart === '14:00') {
      scheduledStaff = solve.grossStaffRequired - 6; // Understaffed by 6 agents
    } else if (int.intervalStart === '13:00') {
      scheduledStaff = solve.grossStaffRequired - 2;
    } else if (int.intervalStart === '09:00') {
      scheduledStaff = solve.grossStaffRequired + 4;
    }

    const delta = scheduledStaff - solve.grossStaffRequired;
    let coverageStatus: 'SURPLUS' | 'BALANCED' | 'UNDERSTAFFED' | 'CRITICAL' = 'BALANCED';
    if (delta <= -5) coverageStatus = 'CRITICAL';
    else if (delta < 0) coverageStatus = 'UNDERSTAFFED';
    else if (delta >= 3) coverageStatus = 'SURPLUS';

    return {
      intervalStart: int.intervalStart,
      channel: 'VOICE',
      forecastVolume: int.volume,
      forecastAht: int.ahtSeconds,
      serviceGoal: `${int.serviceGoalPercent}/${int.thresholdSeconds}`,
      targetOccupancy: 0.85,
      shrinkagePercent: 0.22,
      rawRequiredStaff: solve.rawAgentsRequired,
      netRequiredStaff: solve.netStaffRequired,
      grossRequiredStaff: solve.grossStaffRequired,
      requiredFte: Number((solve.grossStaffRequired * 0.95).toFixed(1)),
      scheduledStaff,
      scheduledFte: Number((scheduledStaff * 0.95).toFixed(1)),
      deltaStaff: delta,
      coverageStatus,
    };
  });
}

