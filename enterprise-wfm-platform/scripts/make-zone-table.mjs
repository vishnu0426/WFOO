// Builds src/services/zoneTable.ts from the IANA time zone database (public domain): zone.tab gives each zone's country, backward gives the old names that now point at a new one.
// Usage: node scripts/make-zone-table.mjs <zone.tab> <backward> > src/services/zoneTable.ts     (files from https://data.iana.org/time-zones/tzdb/)
import { readFileSync } from 'node:fs';

const [zoneTab, backward] = process.argv.slice(2).map((f) => readFileSync(f, 'utf8'));
const zones = zoneTab.split('\n').filter((l) => l && !l.startsWith('#')).map((l) => { const [cc, , id] = l.split('\t'); return [id, cc]; }).sort((a, b) => a[0].localeCompare(b[0]));
const ids = new Set(zones.map((z) => z[0]));
const aliases = {};
for (const l of backward.split('\n')) {
  const m = /^Link\s+(\S+)\s+(\S+)/.exec(l);
  if (m && ids.has(m[1]) && !ids.has(m[2]) && m[2].includes('/') && /^[A-Z][A-Za-z]+\//.test(m[2]) && !/^(US|Canada|Brazil|Chile|Mexico|Etc)\//.test(m[2])) aliases[m[2]] = m[1];
}
const out = [];
out.push('/**');
out.push(' * Every time zone with its country, and the old names that now mean another zone. Generated by scripts/make-zone-table.mjs from the IANA time zone database');
out.push(` * (public domain, https://www.iana.org/time-zones), ${new Date().toISOString().slice(0, 10)}. Do not edit by hand: run the script again when the database changes.`);
out.push(' */');
out.push('/** [zone, ISO country code] */');
out.push('export const ZONES: readonly (readonly [string, string])[] = [');
for (const [id, cc] of zones) out.push(`  ['${id}', '${cc}'],`);
out.push('];');
out.push('');
out.push('/** old name -> current name (Asia/Calcutta -> Asia/Kolkata) */');
out.push('export const ZONE_ALIASES: Readonly<Record<string, string>> = {');
for (const [k, v] of Object.entries(aliases).sort()) out.push(`  '${k}': '${v}',`);
out.push('};');
process.stdout.write(out.join('\n') + '\n');
